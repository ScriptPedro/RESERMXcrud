export const TRADUCOES = { 'pt-BR': ptBR, en, es };

// Busca a chave no idioma escolhido; se não existir, cai no português;
// se ainda assim não existir, devolve a própria chave (facilita achar traduções faltando).
export function traduzir(idioma, chave) {
  const dicionario = TRADUCOES[idioma] || TRADUCOES[IDIOMA_PADRAO];
  return dicionario[chave] ?? TRADUCOES[IDIOMA_PADRAO][chave] ?? chave;
}
